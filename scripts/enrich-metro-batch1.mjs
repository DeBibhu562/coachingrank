function main() {
  console.log('Loading current rankings...');
  const currentRankings = JSON.parse(fs.readFileSync(RANKINGS_JSON_FILE, 'utf8'));
  const map = new Map(currentRankings.map((r) => [r.slug, r]));

  let enrichedCount = 0;
  for (const [slug, enrichment] of Object.entries(METRO_BATCH_1_ENRICHMENTS)) {
    const existing = map.get(slug);
    if (!existing) {
      console.warn(`Slug not found: ${slug}`);
      continue;
    }

    // Merge enrichment
    existing.title = enrichment.title || existing.title;
    existing.metaDescription = enrichment.metaDescription || existing.metaDescription;
    existing.editorialGuide = enrichment.editorialGuide || existing.editorialGuide;
    if (enrichment.faqs && enrichment.faqs.length > 0) {
      existing.faqs = enrichment.faqs;
    }

    if (enrichment.institutes && enrichment.institutes.length > 0) {
      existing.institutes = enrichment.institutes;
    }

    enrichedCount++;
    console.log(`Enriched: ${slug} (${existing.institutes.length} institutes, guide: true)`);
  }

  const updatedRankings = Array.from(map.values());
  fs.writeFileSync(RANKINGS_JSON_FILE, JSON.stringify(updatedRankings, null, 2), 'utf8');
  console.log(`\nSuccessfully enriched ${enrichedCount} flagship metro pages in ${RANKINGS_JSON_FILE}!`);
}

main();
